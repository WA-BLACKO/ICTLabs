/* =====================================================
   ICT LAB RECORDING PROGRESS SYSTEM
===================================================== */

const RECORDING_PROGRESS_KEY =
    "ictLabRecordingProgress";


function getRecordingProgress() {

    try {

        return JSON.parse(
            localStorage.getItem(
                RECORDING_PROGRESS_KEY
            )
        ) || {};

    }

    catch {

        return {};

    }

}


function saveRecordingProgress(progress) {

    localStorage.setItem(
        RECORDING_PROGRESS_KEY,
        JSON.stringify(progress)
    );

}


/* =====================================================
   CHECK VIDEO
===================================================== */

function isRecordingCompleted(
    lessonId,
    videoIndex
) {

    const progress =
        getRecordingProgress();


    return !!(
        progress[lessonId] &&
        progress[lessonId][videoIndex]
    );

}


/* =====================================================
   COMPLETE VIDEO
===================================================== */

function completeRecording(
    lessonId,
    videoIndex
) {

    const progress =
        getRecordingProgress();


    if (!progress[lessonId]) {

        progress[lessonId] = {};

    }


    /*
       Already completed?
       Don't count twice.
    */

    if (
        progress[lessonId][videoIndex]
    ) {

        updateLessonProgress(
            lessonId
        );

        return;

    }


    progress[lessonId][videoIndex] = {

        completed: true,

        completedAt:
            new Date().toISOString()

    };


    saveRecordingProgress(
        progress
    );


    updateVideoCompletedUI(
        videoIndex
    );


    updateLessonProgress(
        lessonId
    );


    checkLessonCompleted(
        lessonId
    );

}


